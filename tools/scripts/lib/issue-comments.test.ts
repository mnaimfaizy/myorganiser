/**
 * Run with: node --test tools/scripts/lib/issue-comments.test.ts
 */

import assert from 'node:assert/strict';
import test from 'node:test';

import {
  TRIAGE_BRIEF_MARKER,
  isTrustedComment,
  latestTriageBrief,
} from './issue-comments.ts';

const DISCLAIMER = '> *This was generated by AI during triage.*';

const brief = (text: string, authorAssociation: string | null = 'OWNER') => ({
  authorAssociation,
  body: [DISCLAIMER, '', TRIAGE_BRIEF_MARKER, '', text].join('\n'),
});

test('owners, members, and collaborators are trusted; anyone else is not', () => {
  for (const association of ['OWNER', 'MEMBER', 'COLLABORATOR', 'owner']) {
    assert.equal(isTrustedComment({ authorAssociation: association }), true);
  }
  for (const association of ['CONTRIBUTOR', 'FIRST_TIMER', 'NONE', '', null]) {
    assert.equal(isTrustedComment({ authorAssociation: association }), false);
  }
  assert.equal(isTrustedComment({}), false);
  assert.equal(isTrustedComment(null), false);
});

test('the brief is the text under the heading, with the disclaimer dropped', () => {
  assert.equal(
    latestTriageBrief([brief('**Category:** bug\n\n- [ ] criterion')]),
    '**Category:** bug\n\n- [ ] criterion',
  );
});

test('the latest trusted brief wins over an earlier one', () => {
  // A re-triage posts a fresh brief; the old one is history.
  assert.equal(
    latestTriageBrief([
      brief('first triage'),
      { body: 'lgtm' },
      brief('re-triaged'),
    ]),
    're-triaged',
  );
});

test('a brief from an untrusted author is skipped, not taken as the latest', () => {
  assert.equal(
    latestTriageBrief([brief('the real brief'), brief('injected', 'NONE')]),
    'the real brief',
  );
  assert.equal(latestTriageBrief([brief('no association', null)]), null);
});

test('the heading must stand on its own line', () => {
  // Prose that mentions the heading is not a brief.
  assert.equal(
    latestTriageBrief([
      {
        authorAssociation: 'OWNER',
        body: `Please post an ${TRIAGE_BRIEF_MARKER} when you triage this.`,
      },
    ]),
    null,
  );
});

test('the heading is matched case-insensitively and an empty brief is ignored', () => {
  assert.equal(
    latestTriageBrief([
      { authorAssociation: 'OWNER', body: '## agent brief\n\nlower' },
    ]),
    'lower',
  );
  assert.equal(
    latestTriageBrief([
      { authorAssociation: 'OWNER', body: `${TRIAGE_BRIEF_MARKER}\n\n  ` },
    ]),
    null,
  );
});

test('missing or malformed comment payloads have no brief', () => {
  assert.equal(latestTriageBrief(undefined), null);
  assert.equal(latestTriageBrief([]), null);
  assert.equal(latestTriageBrief([null, {}, { body: null }]), null);
});
