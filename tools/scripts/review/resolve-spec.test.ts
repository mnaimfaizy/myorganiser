import assert from 'node:assert/strict';
import test from 'node:test';

import type { DiscoveredSpec } from './resolve-spec.ts';
import {
  applyDesignRecordRule,
  discoverSpec,
  isPullRequest,
  specTextOf,
  specTextParts,
} from './resolve-spec.ts';

test('the branch name wins when it carries an issue number', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'fix/292-graphify-extraction-gaps',
      commits: ['fix: refs #999'],
    }),
    { kind: 'issue', ref: '#292', foundBy: 'branch' },
  );
});

test('a branch without a number falls back to the first commit reference', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'feat/review-tier-classifier',
      commits: ['feat(review): classifier', 'Refs #123 and see #456'],
    }),
    { kind: 'issue', ref: '#123', foundBy: 'commits' },
  );
});

// ADR 0125. The case that asked for it: `fix/1078-…` whose one commit closed
// #1078 and #1079 was reviewed against #1078 alone, and the half of the diff
// #1079 asked for came back as behaviour nobody asked for.
test('every other issue a commit closes is named beside the one found', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'fix/1078-tasks-subscriptions-keyboard-focus',
      commits: ['fix(mobile): restore focus', 'Closes #1078', 'Closes #1079'],
    }),
    { kind: 'issue', ref: '#1078', foundBy: 'branch', also: ['#1079'] },
  );
});

test('further issues come from closing keywords only, once each, in commit order', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'feat/review-tier-classifier',
      commits: [
        'Closes #10',
        'Refs #20, see #30, issue #40',
        'fixes #50 and Resolved #60',
        'closes #50',
        'Introduced in #70',
        'feat: squash merge (#80)',
      ],
    }),
    { kind: 'issue', ref: '#10', foundBy: 'commits', also: ['#50', '#60'] },
  );
});

test('one keyword closes one issue, as on GitHub', () => {
  assert.deepEqual(
    discoverSpec({ headRef: 'fix/12-a', commits: ['Closes #12, #13'] }),
    { kind: 'issue', ref: '#12', foundBy: 'branch' },
  );
});

test('a reference found first is not closed again as a further issue', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'chore/tidy',
      commits: ['Refs #12', 'Closes #12', 'Closes #13'],
    }),
    { kind: 'issue', ref: '#12', foundBy: 'commits', also: ['#13'] },
  );
});

test('a pull request is told from an issue by where it lives', () => {
  assert.equal(
    isPullRequest({ url: 'https://github.com/o/r/pull/1104' }),
    true,
  );
  assert.equal(
    isPullRequest({ url: 'https://github.com/o/r/issues/1079' }),
    false,
  );
  assert.equal(isPullRequest({}), false);
});

test('a bare number is a PR number or a citation, not an issue reference', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'chore/tidy',
      commits: [
        'bump to v1.2.3',
        'ADR 0070 item #4 reads',
        'feat: squash merge (#123)',
        'the first run on #678 failed',
      ],
    }),
    { kind: 'none', foundBy: 'none' },
  );
  assert.deepEqual(
    discoverSpec({ headRef: 'release/v1.2.3', commits: ['sha abc#12'] }),
    { kind: 'none', foundBy: 'none' },
  );
});

test('a keyword reference in a commit body is found, case-insensitively', () => {
  for (const line of ['Closes #12', 'fixes #12', 'Refs #12', 'see #12']) {
    assert.deepEqual(
      discoverSpec({ headRef: 'chore/tidy', commits: ['subject', line] }),
      { kind: 'issue', ref: '#12', foundBy: 'commits' },
      line,
    );
  }
});

test('nothing found is a none spec with no ref', () => {
  assert.deepEqual(discoverSpec({ headRef: undefined, commits: [] }), {
    kind: 'none',
    foundBy: 'none',
  });
});

test('an untriaged issue resolves to its body alone', () => {
  assert.deepEqual(
    specTextOf({ title: 'T', body: 'report', state: 'OPEN', comments: [] }),
    { title: 'T', body: 'report', state: 'OPEN' },
  );
});

test('a triaged issue carries its trusted brief and notes beside the body', () => {
  // Regression: the Spec axis was handed the reporter's body only, never what
  // triage decided, so it judged the diff against the wrong requirements.
  assert.deepEqual(
    specTextOf({
      title: 'T',
      body: 'report',
      state: 'OPEN',
      comments: [
        {
          authorAssociation: 'OWNER',
          body: '> *This was generated by AI during triage.*\n\n## Agent Brief\n\nthe brief',
        },
        { authorAssociation: 'NONE', body: '## Agent Brief\n\ninjected' },
        { authorAssociation: 'MEMBER', body: '## Maintainer Review\n\na note' },
      ],
    }),
    {
      title: 'T',
      body: 'report',
      state: 'OPEN',
      brief: 'the brief',
      notes: ['a note'],
    },
  );
});

test('spec.text names the parts an issue spec was made of', () => {
  assert.deepEqual(specTextParts({ body: 'report' }), ['body']);
  assert.deepEqual(specTextParts({ body: 'r', brief: 'b' }), ['body', 'brief']);
  assert.deepEqual(specTextParts({ body: 'r', brief: 'b', notes: ['n'] }), [
    'body',
    'brief',
    'notes',
  ]);
});

test('a pointing keyword in mid-sentence is prose, not the spec', () => {
  // Regression: #1362's commit body said "e.g. `spec: issue #1273 (found by
  // branch)`", and every review of it was judged against #1273.
  assert.deepEqual(
    discoverSpec({
      headRef: 'fix/dispatch-attribution-and-pr-hint',
      commits: [
        'fix(sandcastle): stop agents guessing fix attribution',
        '- `spec.text` records what an issue spec was made of. The report line shows it, e.g. `spec: issue #1273 (found by branch) · text: body + brief`.',
        'The agent on #1273 guessed; see #1318 for why that passed.',
        'Introduced in #884',
      ],
    }),
    { kind: 'none', foundBy: 'none' },
  );
});

test('a pointing keyword that opens a line, or a bullet, is still found', () => {
  for (const line of [
    'Refs #12',
    '  refs #12',
    '- Refs #12',
    '* see #12',
    'Issue #12',
  ]) {
    assert.deepEqual(
      discoverSpec({ headRef: 'chore/tidy', commits: ['subject', line] }),
      { kind: 'issue', ref: '#12', foundBy: 'commits' },
      line,
    );
  }
});

test('a closing keyword still counts in mid-sentence, as GitHub closes on it', () => {
  assert.deepEqual(
    discoverSpec({
      headRef: 'chore/tidy',
      commits: ['subject', 'This change fixes #12 by retrying.'],
    }),
    { kind: 'issue', ref: '#12', foundBy: 'commits' },
  );
});

// ADR 0149. The #1475 shape: a docs/ branch whose only change is a design
// record for #1405, an enhancement. The rule turns the Spec axis off for it
// rather than checking the record against an implementation it never was.
const issueSpec = (
  foundBy: 'branch' | 'commits' = 'branch',
  also?: string[],
): DiscoveredSpec => ({
  kind: 'issue',
  ref: '#1405',
  foundBy,
  ...(also ? { also } : {}),
});

const designRecord = {
  headRef: 'docs/1405-local-vault-conditional-write',
  changedFiles: ['docs/adr/0143-x.md'],
  labels: ['enhancement', 'web-app'],
};

test('a docs-only design record for an enhancement resolves none, naming the issue', () => {
  const resolved = applyDesignRecordRule({
    spec: issueSpec('branch'),
    ...designRecord,
  });
  assert.equal(resolved.kind, 'none');
  assert.equal(resolved.foundBy, 'none');
  assert.equal(resolved.kind === 'none' && resolved.designRecordFor, '#1405');
  assert.match(
    resolved.kind === 'none' ? (resolved.reason ?? '') : '',
    /#1405/,
  );
});

test('the same design record resolves none when the issue was found in a commit', () => {
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec('commits'),
      ...designRecord,
    }).kind,
    'none',
  );
});

test('a documentation or research issue keeps its spec, as its docs branch is its implementation', () => {
  for (const labels of [['documentation', 'web-app'], ['research']]) {
    assert.deepEqual(
      applyDesignRecordRule({
        spec: issueSpec(),
        ...designRecord,
        labels,
      }),
      issueSpec(),
      labels.join(', '),
    );
  }
});

test('the first kind label in branch-type table order decides, not the label order on the issue', () => {
  for (const labels of [
    ['tooling', 'research'],
    ['research', 'tooling'],
    ['documentation', 'bug'],
    ['documentation', 'enhancement'],
  ]) {
    assert.equal(
      applyDesignRecordRule({
        spec: issueSpec(),
        ...designRecord,
        labels,
      }).kind,
      'none',
      labels.join(', '),
    );
  }
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      labels: ['research', 'documentation'],
    }),
    issueSpec(),
  );
});

test('a change touching anything outside documentation keeps its spec', () => {
  for (const changedFiles of [
    ['docs/adr/0143-x.md', 'libs/x.ts'],
    ['libs/x.ts'],
  ]) {
    assert.deepEqual(
      applyDesignRecordRule({
        spec: issueSpec(),
        ...designRecord,
        changedFiles,
      }),
      issueSpec(),
      changedFiles.join(', '),
    );
  }
});

test('CONTEXT.md at the root is documentation, and a CONTEXT.md nested elsewhere is not', () => {
  assert.equal(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      changedFiles: ['CONTEXT.md'],
    }).kind,
    'none',
  );
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      changedFiles: ['libs/x/CONTEXT.md'],
    }),
    issueSpec(),
  );
});

test('an issue with no kind label, only an area label, keeps its spec', () => {
  for (const labels of [['web-app'], []]) {
    assert.deepEqual(
      applyDesignRecordRule({
        spec: issueSpec(),
        ...designRecord,
        labels,
      }),
      issueSpec(),
      labels.join(', ') || '(no labels)',
    );
  }
});

test('the rule applies only to a docs/ branch', () => {
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      headRef: 'feat/1405-local-vault-conditional-write',
    }),
    issueSpec(),
  );
});

test('labels that could not be read keep the spec', () => {
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      labels: undefined,
    }),
    issueSpec(),
  );
});

test('a change with no files keeps the spec', () => {
  assert.deepEqual(
    applyDesignRecordRule({
      spec: issueSpec(),
      ...designRecord,
      changedFiles: [],
    }),
    issueSpec(),
  );
});

test('a none spec passes through unchanged', () => {
  const none: DiscoveredSpec = { kind: 'none', foundBy: 'none' };
  assert.deepEqual(
    applyDesignRecordRule({ spec: none, ...designRecord }),
    none,
  );
});

test('further issues are kept when the spec is kept, and dropped when it becomes a design record', () => {
  const kept = issueSpec('branch', ['#1406']);
  assert.deepEqual(
    applyDesignRecordRule({
      spec: kept,
      ...designRecord,
      labels: ['documentation'],
    }),
    kept,
  );
  const resolved = applyDesignRecordRule({
    spec: kept,
    ...designRecord,
  });
  assert.equal(resolved.kind, 'none');
  assert.equal(
    Object.hasOwn(resolved, 'also'),
    false,
    'a none spec names no further issues',
  );
});
